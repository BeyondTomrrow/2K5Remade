"""The guest functions My NFL Eras calls (docs/eras/MOD-PACK-DESIGN.md 6.3).

    python -I tools/eras/check_guest_calls.py           check src/nfl2k5_eras_guest_calls.h
    python -I tools/eras/check_guest_calls.py --write   rewrite it

Every sub_XXXXXXXX the module's sources name (src/nfl2k5_eras*.c, the draft show
included) is one entry of the frozen retail ABI the module depends on. The list
goes to the host (NfModuleInfo.guest_calls) for the dirty-map check under an XBE
pack, and makes a later DLL build mechanical. The check fails when the sources
call a function the list does not have, or the list names one nobody calls.
"""
import glob, os, re, sys

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), '..', '..'))
OUT = os.path.join(ROOT, 'src', 'nfl2k5_eras_guest_calls.h')


def used():
    vas = set()
    for p in sorted(glob.glob(os.path.join(ROOT, 'src', 'nfl2k5_eras*.c'))):
        t = open(p, encoding='utf-8', errors='replace').read()
        t = re.sub(r'/\*.*?\*/', '', t, flags=re.S)
        t = re.sub(r'//[^\n]*', '', t)
        vas.update(int(m, 16) for m in re.findall(r'\bsub_([0-9A-Fa-f]{8})\b', t))
    return sorted(vas)


def listed():
    if not os.path.exists(OUT):
        return None
    return sorted(int(m, 16) for m in re.findall(r'0x([0-9A-F]{8})u', open(OUT, encoding='utf-8').read()))


def write(vas):
    lines = ['/* Generated by tools/eras/check_guest_calls.py: every guest function the My NFL',
             ' * Eras module calls (src/nfl2k5_eras*.c). The retail XBE never changes, so these',
             ' * addresses are a frozen ABI; an XBE pack that rewrites one of them is a',
             ' * compatibility failure (docs/eras/MOD-PACK-DESIGN.md 6.3). Do not edit. */',
             '#ifndef NFL2K5_ERAS_GUEST_CALLS_H', '#define NFL2K5_ERAS_GUEST_CALLS_H', '',
             '#define NFL2K5_ERAS_GUEST_CALL_COUNT %d' % len(vas),
             'static const uint32_t k_eras_guest_calls[NFL2K5_ERAS_GUEST_CALL_COUNT] = {']
    for i in range(0, len(vas), 6):
        lines.append('    ' + ' '.join('0x%08Xu,' % v for v in vas[i:i + 6]))
    lines += ['};', '', '#endif', '']
    open(OUT, 'w', encoding='utf-8', newline='\n').write('\n'.join(lines))


def main():
    vas = used()
    if '--write' in sys.argv:
        write(vas)
        print('%d guest functions -> %s' % (len(vas), os.path.relpath(OUT, ROOT)))
        return 0
    have = listed()
    if have is None:
        print('missing %s (run with --write)' % os.path.relpath(OUT, ROOT))
        return 1
    extra, missing = sorted(set(have) - set(vas)), sorted(set(vas) - set(have))
    for v in missing:
        print('called but not listed: sub_%08X' % v)
    for v in extra:
        print('listed but not called: sub_%08X' % v)
    print('%d guest functions; list %s' % (len(vas), 'OK' if not extra and not missing else 'STALE'))
    return 1 if extra or missing else 0


if __name__ == '__main__':
    sys.exit(main())
