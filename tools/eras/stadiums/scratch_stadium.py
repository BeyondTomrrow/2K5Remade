"""A parametric, from-scratch modern college-football bowl for the NFL 2K5 stadium-pack build.

    generate(variant) -> (tris, mats, textures)

Builds a large elongated double-decker stadium (modelled on the modern Bryant-Denny Stadium) directly in
2K5 centimetres (X across / sideline, Y up, Z along the field / end zones; ground at Y=0). NOTHING is read from
any game: every vertex, strip and texture here is generated by code. The result plugs into coliseum_build's
``build_bundle`` exactly like a converted NCAA model would: ``mats`` maps a material key -> (texture name, kind)
and ``textures`` maps a texture name -> PIL RGBA image. The crowd uses the engine's animated ``crowd`` material
(kind "crowd", tinted per deck through the vertex colours); the videoboard the live ``jumbo_tron`` feed (kind
"jumbo"); seats, concourse walls, roof and the outer facade are flat generated P8 textures (kind "static").

The bowl is a rounded-rectangle "racetrack" plan: straight runs down the two sidelines and the two end zones
with rounded corners, longer in Z than X. A raked lower deck (crimson crowd) rises from just outside the field
border; a vertical fascia / concourse gap; a steeper upper deck (silver crowd); a grey roof canopy cantilevered
inward over the top rows; a solid grey outer facade all the way around; and an elevated videoboard at one end.
"""
from __future__ import annotations

import math
import sys
from pathlib import Path

import numpy as np

_HERE = Path(__file__).resolve().parent
_ROOT = _HERE.parents[2]
for _p in (_HERE, _ROOT / "tools" / "team-creator" / "vendor", _ROOT / "tools" / "team-creator"):
    if str(_p) not in sys.path:
        sys.path.insert(0, str(_p))

import coliseum_build as CB


# --- tunable geometry (centimetres) -------------------------------------------------------------------------
# inner racetrack: straight-section half-extents (corner arc centres at (+-SX, +-SZ)) + inner corner radius.
# SX+R0 / SZ+R0 is the inner edge of the lower bowl; it clears the field border FIELD_HALF=(2700, 5800).
P = dict(
    SX=1250.0, SZ=4650.0, R0=1560.0,          # inner edge: x=+-2810, z=+-6210; elongated (longer in Z)
    ns=10, nc=8,                               # loop samples per straight / per corner
    wall_y=250.0,                              # top of the field-level wall (lower deck starts here)
    # lower deck: raked crowd plane
    low_rows=26, low_rise=82.0, low_tread=125.0,
    # concourse fascia between the decks, then a small setback before the upper deck
    fascia_h=620.0, setback=400.0,
    # upper deck: steeper raked crowd plane
    up_rows=36, up_rise=100.0, up_tread=100.0,
    # roof: a back parapet above the top row, then a grey canopy ring cantilevered inward over the top rows
    parapet_h=460.0, roof_in=2300.0, roof_rise=240.0, roof_fascia=380.0,
    # exterior detail
    brick_h=1500.0,                            # height of the brick base band
    tower_z=3400.0, tower_rise=2400.0, tower_depth=1300.0,   # press tower (west / -x sideline)
    corner_r=1650.0, corner_frac=0.90,         # rounded corner ramp towers
)

# colours (pre-tint). the renderer draws rgb * vertex_colour * 1.15; crowd/jumbo multiply the atlas/feed.
CRIMSON = (150, 18, 48)
CRIMSON_WALL = (120, 20, 40)
SILVER = (208, 212, 218)
CONCRETE = (150, 150, 152)
ROOF = (120, 122, 126)
CROWD_LOWER = (196, 70, 82)      # crimson-tinted lower-deck crowd
CROWD_UPPER = (205, 208, 214)    # neutral upper-deck crowd
WHITE = (238, 238, 238)
BRICK = (120, 60, 45)            # Alabama brick (reddish-brown)
FACADE_GREY = (170, 170, 174)    # upper facade
TRIM = (150, 18, 48)             # crimson accent band
TOWER = (156, 158, 164)          # press tower cladding
WINDOW = (64, 76, 92)            # glazing


def _tint(variant):
    t, w = variant[0], variant[1]
    return tuple(a * b for a, b in zip(CB.TOD_TINT[t], CB.WEATHER_TINT[w]))


# --- textures ------------------------------------------------------------------------------------------------

def _textures():
    from PIL import Image
    rng = np.random.default_rng(77)
    tex = {}

    def img(a):
        return Image.fromarray(np.clip(a, 0, 255).astype(np.uint8), "RGBA")

    # crimson seats: solid crimson with slightly darker seat rows and faint column gaps
    a = np.zeros((64, 64, 4), np.uint8)
    a[..., :3] = CRIMSON
    a[::6, :, :3] = (110, 12, 36)
    a[:, ::16, :3] = (128, 16, 42)
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-6, 7, (64, 64, 3)), 0, 255)
    a[..., 3] = 255
    tex["s77_seat_crimson"] = img(a)

    # silver/white seats
    a = np.zeros((64, 64, 4), np.uint8)
    a[..., :3] = SILVER
    a[::6, :, :3] = (176, 180, 188)
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-6, 7, (64, 64, 3)), 0, 255)
    a[..., 3] = 255
    tex["s77_seat_silver"] = img(a)

    # grey concrete: panels with seams
    a = np.zeros((64, 64, 4), np.uint8)
    a[..., :3] = CONCRETE
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-10, 11, (64, 64, 3)), 0, 255)
    a[::21, :, :3] = (120, 120, 122)
    a[:, ::21, :3] = (120, 120, 122)
    a[..., 3] = 255
    tex["s77_concrete"] = img(a)

    # roof underside: paler ribbed grey
    a = np.zeros((64, 64, 4), np.uint8)
    a[..., :3] = ROOF
    a[:, ::8, :3] = (96, 98, 102)
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-6, 7, (64, 64, 3)), 0, 255)
    a[..., 3] = 255
    tex["s77_roof"] = img(a)

    # dark videoboard surround / bezel
    a = np.zeros((64, 64, 4), np.uint8)
    a[..., :3] = (26, 28, 32)
    a[..., 3] = 255
    tex["s77_board_frame"] = img(a)

    # solid crimson accent trim
    a = np.zeros((16, 16, 4), np.uint8)
    a[..., :3] = TRIM
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-5, 6, (16, 16, 3)), 0, 255)
    a[..., 3] = 255
    tex["s77_trim"] = img(a)

    # brick base: reddish-brown with horizontal mortar courses and offset bricks
    a = np.zeros((128, 128, 4), np.uint8)
    a[..., :3] = BRICK
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-10, 11, (128, 128, 3)), 0, 255)
    for ry in range(0, 128, 11):                               # mortar courses
        a[ry:ry + 2, :, :3] = (150, 128, 112)
        off = 0 if (ry // 11) % 2 == 0 else 11                 # running bond
        for rx in range((off) % 22, 128, 22):                 # vertical head joints
            a[ry:ry + 11, rx:rx + 1, :3] = (150, 128, 112)
    a[..., 3] = 255
    tex["s77_brick"] = img(a)

    # upper facade: grey panels, vertical pilasters/mullions, a window band through the middle (one floor; tiles)
    a = np.zeros((128, 128, 4), np.uint8)
    a[..., :3] = FACADE_GREY
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-6, 7, (128, 128, 3)), 0, 255)
    for mx in range(0, 128, 32):                               # pilasters every 32 px (one bay)
        a[:, mx:mx + 6, :3] = (128, 128, 134)
    a[44:92, :, :3] = np.where((np.arange(128) % 32)[None, :, None] < 6,
                               np.array((128, 128, 134)), np.array(WINDOW)).astype(np.uint8)  # window band + mullions
    a[44:47, :, :3] = (120, 120, 126)                         # window head / sill rails
    a[89:92, :, :3] = (120, 120, 126)
    a[..., 3] = 255
    tex["s77_facade"] = img(a)

    # press tower cladding: grey with a dense window grid and crimson spandrel stripes
    a = np.zeros((128, 128, 4), np.uint8)
    a[..., :3] = TOWER
    a[..., :3] = np.clip(a[..., :3].astype(int) + rng.integers(-6, 7, (128, 128, 3)), 0, 255)
    for ry in range(8, 128, 32):                               # window rows
        a[ry:ry + 20, :, :3] = WINDOW
        a[ry - 4:ry, :, :3] = TRIM                             # crimson spandrel
    for mx in range(0, 128, 20):                               # mullions
        a[:, mx:mx + 4, :3] = (128, 130, 136)
    a[..., 3] = 255
    tex["s77_tower"] = img(a)
    return tex


# --- the racetrack plan --------------------------------------------------------------------------------------

def _racetrack():
    SX, SZ, R0, ns, nc = P["SX"], P["SZ"], P["R0"], P["ns"], P["nc"]
    loop = []   # (bx, bz, nx, nz): point on the inner loop (radius R0) and its outward unit normal

    def straight(p0, p1, nrm, count):
        for k in range(count):
            t = k / count
            loop.append((p0[0] + (p1[0] - p0[0]) * t, p0[1] + (p1[1] - p0[1]) * t, nrm[0], nrm[1]))

    def corner(cx, cz, a0, a1, count):
        for k in range(count):
            a = a0 + (a1 - a0) * (k / count)
            nx, nz = math.cos(a), math.sin(a)
            loop.append((cx + R0 * nx, cz + R0 * nz, nx, nz))

    straight((SX + R0, SZ), (SX + R0, -SZ), (1, 0), ns)
    corner(SX, -SZ, 0.0, -math.pi / 2, nc)
    straight((SX, -(SZ + R0)), (-SX, -(SZ + R0)), (0, -1), ns)
    corner(-SX, -SZ, -math.pi / 2, -math.pi, nc)
    straight((-(SX + R0), -SZ), (-(SX + R0), SZ), (-1, 0), ns)
    corner(-SX, SZ, math.pi, math.pi / 2, nc)
    straight((-SX, SZ + R0), (SX, SZ + R0), (0, 1), ns)
    corner(SX, SZ, math.pi / 2, 0.0, nc)

    # cumulative arc length (n+1 entries, last = full perimeter) for the U texture coordinate
    cumu = [0.0]
    n = len(loop)
    for j in range(n):
        x0, z0 = loop[j][0], loop[j][1]
        x1, z1 = loop[(j + 1) % n][0], loop[(j + 1) % n][1]
        cumu.append(cumu[-1] + math.hypot(x1 - x0, z1 - z0))
    return loop, cumu


def _ring(s, h, y):
    return (s[0] + h * s[2], y, s[1] + h * s[3])


def _band(tris, loop, cumu, hA, yA, hB, yB, mat, col, uscale, vA, vB, double=True):
    """A ring of quads around the loop from edge A (offset hA, height yA) to edge B (offset hB, height yB)."""
    n = len(loop)
    cA = tuple(col) + (255,)
    for j in range(n):
        s0, s1 = loop[j], loop[(j + 1) % n]
        Pp = [_ring(s0, hA, yA), _ring(s1, hA, yA), _ring(s1, hB, yB), _ring(s0, hB, yB)]
        u0, u1 = cumu[j] / uscale, cumu[j + 1] / uscale
        UV = [(u0, vA), (u1, vA), (u1, vB), (u0, vB)]
        C = [cA, cA, cA, cA]
        for a, b, c in ((0, 1, 2), (0, 2, 3)):
            tris.append(CB.Tri(mat, [Pp[a], Pp[b], Pp[c]], [UV[a], UV[b], UV[c]], [C[a], C[b], C[c]]))
        if double:
            for a, b, c in ((0, 2, 1), (0, 3, 2)):
                tris.append(CB.Tri(mat, [Pp[a], Pp[b], Pp[c]], [UV[a], UV[b], UV[c]], [C[a], C[b], C[c]]))


def _flat_quad(tris, mat, Pp, col, uv=None, double=True):
    C = [tuple(col) + (255,)] * 4
    if uv is None:
        uv = [(0, 0), (1, 0), (1, 1), (0, 1)]
    for a, b, c in ((0, 1, 2), (0, 2, 3)):
        tris.append(CB.Tri(mat, [Pp[a], Pp[b], Pp[c]], [uv[a], uv[b], uv[c]], [C[a], C[b], C[c]]))
    if double:
        for a, b, c in ((0, 2, 1), (0, 3, 2)):
            tris.append(CB.Tri(mat, [Pp[a], Pp[b], Pp[c]], [uv[a], uv[b], uv[c]], [C[a], C[b], C[c]]))


def _box(tris, x0, x1, z0, z1, y0, y1, mat, col, us=700.0, vfloors=1.0):
    """An axis-aligned rectangular box (4 walls + top), clad in ``mat``."""
    c = [(x0, z0), (x1, z0), (x1, z1), (x0, z1)]
    for k in range(4):
        (ax, az), (bx, bz) = c[k], c[(k + 1) % 4]
        uu = math.hypot(bx - ax, bz - az) / us
        _flat_quad(tris, mat, [(ax, y0, az), (bx, y0, bz), (bx, y1, bz), (ax, y1, az)], col,
                   uv=[(0, 0), (uu, 0), (uu, vfloors), (0, vfloors)])
    _flat_quad(tris, mat, [(x0, y1, z0), (x1, y1, z0), (x1, y1, z1), (x0, y1, z1)], col)


def _cylinder(tris, cx, cz, r, y0, y1, mat, col, nseg=16, us=700.0, vfloors=4.0, cap=True, capcol=None):
    """A vertical cylindrical tower (outer wall + optional top cap)."""
    circ = 2 * math.pi * r
    for k in range(nseg):
        a0, a1 = 2 * math.pi * k / nseg, 2 * math.pi * (k + 1) / nseg
        p0 = (cx + r * math.cos(a0), cz + r * math.sin(a0))
        p1 = (cx + r * math.cos(a1), cz + r * math.sin(a1))
        u0, u1 = circ * k / nseg / us, circ * (k + 1) / nseg / us
        _flat_quad(tris, mat, [(p0[0], y0, p0[1]), (p1[0], y0, p1[1]), (p1[0], y1, p1[1]), (p0[0], y1, p0[1])],
                   col, uv=[(u0, 0), (u1, 0), (u1, vfloors), (u0, vfloors)])
    if cap:
        cc = tuple(capcol or col) + (255,)
        for k in range(nseg):
            a0, a1 = 2 * math.pi * k / nseg, 2 * math.pi * (k + 1) / nseg
            p0 = (cx + r * math.cos(a0), y1, cz + r * math.sin(a0))
            p1 = (cx + r * math.cos(a1), y1, cz + r * math.sin(a1))
            tris.append(CB.Tri(mat, [(cx, y1, cz), p0, p1], [(0.5, 0.5), (0, 0), (1, 0)], [cc, cc, cc]))


# --- the bowl ------------------------------------------------------------------------------------------------

def generate(variant="dd"):
    tint = _tint(variant)

    def tc(rgb):   # vertex colour after the time-of-day / weather tint
        return tuple(int(max(0, min(255, round(ch * t)))) for ch, t in zip(rgb, tint))

    loop, cumu = _racetrack()
    tris = []

    # vertical heights / horizontal offsets of each deck edge
    wall_y = P["wall_y"]
    h_low0, y_low0 = 0.0, wall_y
    h_low1 = P["low_rows"] * P["low_tread"]
    y_low1 = wall_y + P["low_rows"] * P["low_rise"]
    y_fascia = y_low1 + P["fascia_h"]
    h_up0 = h_low1 + P["setback"]
    y_up0 = y_fascia
    h_up1 = h_up0 + P["up_rows"] * P["up_tread"]
    y_up1 = y_up0 + P["up_rows"] * P["up_rise"]
    y_parapet = y_up1 + P["parapet_h"]
    h_roof_in = h_up1 - P["roof_in"]
    y_roof = y_parapet + P["roof_rise"]

    # field-level wall (ground up to the lower deck foot), crimson
    _band(tris, loop, cumu, 0.0, 0.0, 0.0, wall_y, "s77_seat_crimson", tc(CRIMSON_WALL), 600.0, 0.0, 0.5)

    # lower deck: raked crimson crowd. tile V so it reads as many rows.
    _band(tris, loop, cumu, h_low0, y_low0, h_low1, y_low1, "crowd", tc(CROWD_LOWER), 230.0,
          0.0, float(P["low_rows"]))
    # a crimson seat strip just behind the lower deck foot for structure
    _band(tris, loop, cumu, h_low0, y_low0, h_low0 + 120.0, y_low0 + 60.0, "s77_seat_crimson",
          tc(WHITE), 300.0, 0.0, 1.0)

    # concourse fascia (vertical, grey) between the decks
    _band(tris, loop, cumu, h_low1, y_low1, h_low1, y_fascia, "s77_concrete", tc(CONCRETE), 900.0, 0.0, 1.0)
    # concourse slab connecting fascia top to the upper-deck foot
    _band(tris, loop, cumu, h_low1, y_fascia, h_up0, y_up0, "s77_concrete", tc(CONCRETE), 900.0, 0.0, 0.3)

    # upper deck: raked silver crowd
    _band(tris, loop, cumu, h_up0, y_up0, h_up1, y_up1, "crowd", tc(CROWD_UPPER), 210.0,
          0.0, float(P["up_rows"]))

    # outer facade, articulated: brick base, crimson stripe, windowed upper facade, crimson top band, parapet
    brick_top = P["brick_h"]
    y_face1 = y_up1
    floors = max(2.0, round((y_face1 - brick_top - 150.0) / 850.0))
    _band(tris, loop, cumu, h_up1, 0.0, h_up1, brick_top, "s77_brick", tc(WHITE), 650.0, 0.0, 1.0)
    _band(tris, loop, cumu, h_up1, brick_top, h_up1, brick_top + 160.0, "s77_trim", tc(WHITE), 900.0, 0.0, 1.0)
    _band(tris, loop, cumu, h_up1, brick_top + 160.0, h_up1, y_face1, "s77_facade", tc(WHITE), 700.0, 0.0, floors)
    _band(tris, loop, cumu, h_up1, y_face1, h_up1, y_face1 + 150.0, "s77_trim", tc(WHITE), 900.0, 0.0, 1.0)
    # back parapet above the crimson band
    _band(tris, loop, cumu, h_up1, y_face1 + 150.0, h_up1, y_parapet, "s77_concrete", tc(CONCRETE), 900.0, 0.0, 0.4)
    # roof canopy: grey ring cantilevered inward over the top rows, sloping slightly up toward the field
    _band(tris, loop, cumu, h_up1, y_parapet, h_roof_in, y_roof, "s77_roof", tc(ROOF), 700.0, 0.0, 2.2)
    # roof front lip: a crimson fascia facing the field (Alabama accent, seen inside and out)
    _band(tris, loop, cumu, h_roof_in, y_roof, h_roof_in, y_roof - P["roof_fascia"], "s77_trim",
          tc(WHITE), 900.0, 0.0, 1.0)

    _videoboard(tris, tc)
    _press_tower(tris, tc, h_up1, y_up1)
    _corner_towers(tris, tc, h_up1)

    mats = {
        "crowd": ("crowd", "crowd"),
        "jumbo_tron": ("jumbo_tron", "jumbo"),
        "s77_seat_crimson": ("s77_seat_crimson", "static"),
        "s77_seat_silver": ("s77_seat_silver", "static"),
        "s77_concrete": ("s77_concrete", "static"),
        "s77_roof": ("s77_roof", "static"),
        "s77_board_frame": ("s77_board_frame", "static"),
        "s77_trim": ("s77_trim", "static"),
        "s77_brick": ("s77_brick", "static"),
        "s77_facade": ("s77_facade", "static"),
        "s77_tower": ("s77_tower", "static"),
    }
    return tris, mats, _textures()


def _press_tower(tris, tc, h_up1, y_up1):
    """A tall press / suite tower above the roof on the west (-x) sideline, taller than the rest of the bowl."""
    x_out = -(P["SX"] + P["R0"] + h_up1)          # the -x facade plane
    x_in = x_out + P["tower_depth"]
    z = P["tower_z"]
    y0 = y_up1 - 300.0                            # springs from just below the roofline
    y1 = y_up1 + P["tower_rise"]
    _box(tris, x_out, x_in, -z, z, y0, y1, "s77_tower", tc(TOWER), us=700.0, vfloors=(y1 - y0) / 650.0)
    # crimson cap band along the very top
    _box(tris, x_out - 40.0, x_in + 40.0, -z - 40.0, z + 40.0, y1, y1 + 160.0, "s77_trim", tc(WHITE))


def _corner_towers(tris, tc, h_up1):
    """Rounded ramp / stair towers bulging out at the four corners, so the silhouette isn't a plain oval."""
    SX, SZ, R0 = P["SX"], P["SZ"], P["R0"]
    rad = R0 + h_up1                              # facade corner radius
    r = P["corner_r"]
    y1 = (P["wall_y"] + P["low_rows"] * P["low_rise"] + P["fascia_h"]
          + P["up_rows"] * P["up_rise"]) * P["corner_frac"]
    for sx in (1, -1):
        for sz in (1, -1):
            # centre on the facade corner diagonal, pushed out so the tower bulges beyond the oval
            d = (rad + r * 0.45) / math.sqrt(2.0)
            cx = sx * (SX + d)
            cz = sz * (SZ + d)
            _cylinder(tris, cx, cz, r, 0.0, y1, "s77_facade", tc(WHITE), nseg=18, us=650.0,
                      vfloors=max(3.0, y1 / 850.0), cap=True, capcol=tc(ROOF))
            _cylinder(tris, cx, cz, r + 20.0, y1, y1 + 180.0, "s77_trim", tc(WHITE), nseg=18, us=900.0,
                      vfloors=1.0, cap=False)


def _videoboard(tris, tc):
    """A large elevated videoboard above the south (+Z) end zone, facing the field (-Z)."""
    SZ, R0 = P["SZ"], P["R0"]
    z = SZ + R0 + 1100.0           # just in front of the south upper deck
    bw, by0, by1 = 3100.0, 2900.0, 4600.0
    fr = 220.0                     # frame thickness
    # dark frame (slightly behind the screen)
    _flat_quad(tris, "s77_board_frame",
               [(-bw - fr, by0 - fr, z + 30), (bw + fr, by0 - fr, z + 30),
                (bw + fr, by1 + fr, z + 30), (-bw - fr, by1 + fr, z + 30)], tc((26, 28, 32)))
    # the live-feed screen (jumbo_tron)
    _flat_quad(tris, "jumbo_tron",
               [(-bw, by0, z), (bw, by0, z), (bw, by1, z), (-bw, by1, z)],
               (210, 230, 255), uv=[(0, 0), (0.625, 0), (0.625, 0.875), (0, 0.875)])


if __name__ == "__main__":
    for v in ("dd",):
        t, m, tx = generate(v)
        print(v, "tris", len(t), "mats", sorted(m), "textures", sorted(tx))
