def check(entity, rows, base, derived):
    keys = set()
    for sel, key in rows:
        if key in keys:
            raise SystemExit('%s: key %s used twice' % (entity, key))
        keys.add(key)
        if sel in base:
            e = base[sel]
            getter = e['player_getter' if entity == 'player' else 'team_getter']
            if not getter:
                raise SystemExit('%s: selector 0x%02X has no %s getter' % (entity, sel, entity))
        elif sel in derived:
            for i in derived[sel]['inputs']:
                if int(i, 16) not in base and int(i, 16) not in derived:
                    raise SystemExit('%s: derived 0x%02X input %s unknown' % (entity, sel, i))
        else:
            raise SystemExit('%s: selector 0x%02X not in %s' % (entity, sel, SRC.name))


def label(sel, entity, base, derived):
    e = base.get(sel) or derived.get(sel)
    for l in e['labels']:
        if l.startswith(entity + ':') and l.endswith('@0'):
            return l[len(entity) + 1:-2]
    return ''


def render(base, derived, sha):
    out = ['/* Generated by tools/eras/result_capture/capture_table.py from',
           ' * data/eras/stat_selectors_2k5.json (XBE sha256 %s...). Do not edit. */' % sha[:16],
           '#ifndef NFL2K5_ERAS_SELECTORS_H', '#define NFL2K5_ERAS_SELECTORS_H', '',
           'typedef struct { unsigned char selector; const char *key; } ErasSelector;', '']
    for entity, name, rows in (('player', 'k_eras_player_box', PLAYER), ('team', 'k_eras_team_box', TEAM)):
        out.append('/* %s box, scope 0 (%s) */' % (entity, 'sub_000CB240' if entity == 'player' else 'sub_000CB2D0'))
        out.append('static const ErasSelector %s[] = {' % name)
        for sel, key in rows:
            lab = label(sel, entity, base, derived)
            kind = 'derived' if sel in derived else 'type %d' % base[sel]['type']
            out.append('    { 0x%02X, "%s" },%s' % (sel, key, '  /* %s%s */' % (kind, (', "%s"' % lab) if lab else '')))
        out.append('};')
        out.append('#define %s_COUNT %d' % (name.upper()[2:], len(rows)))
        out.append('')
    out.append('#endif')
    return '\r\n'.join(out) + '\r\n'


def main():
    d = json.loads(SRC.read_text(encoding='utf-8'))
    base = {e['selector']: e for e in d['base_selectors']}
    derived = {e['selector']: e for e in d['derived_selectors']}
    check('player', PLAYER, base, derived)
    check('team', TEAM, base, derived)
    if not base[0x5B]['per_period_scopes']:
        raise SystemExit('team 0x5B is expected to answer scopes 1..5')
    text = render(base, derived, d['source']['sha256'])
    if '--check' in sys.argv:
        ok = OUT.exists() and OUT.read_bytes() == text.encode('ascii')
        print('%s: %s' % (OUT.name, 'up to date' if ok else 'STALE, rerun without --check'))
        return 0 if ok else 1
    OUT.write_bytes(text.encode('ascii'))
    print('wrote %s: %d player, %d team selectors' % (OUT, len(PLAYER), len(TEAM)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
