"""My NFL Eras: the box-score selector table compiled into the game.

    python -I tools/eras/result_capture/capture_table.py [--check]

Input:  data/eras/stat_selectors_2k5.json (written by stat_selectors.py from the
        retail XBE; docs/eras/research/RESULT-CAPTURE.md section 4.4).
Output: src/nfl2k5_eras_selectors.h, two static tables {selector, key} that
        src/nfl2k5_eras_capture.c reads at the final whistle:
          * player box, scope 0, through sub_000CB240;
          * team box, scope 0, through sub_000CB2D0.
        Team points by period (0x5B scopes 1..5) are read separately.

Every selector is checked against the JSON: it must exist (base or derived),
a base selector must have a getter for its entity, and a derived selector's
inputs must exist. --check only verifies that the header is up to date.
The keys are this project's names; where the game labels a selector, the
first label is kept as a comment. Selectors whose meaning is not settled
(team 0x62, 0x5F units, player 0x30, 0x63 at scope 0) keep neutral keys.
"""
