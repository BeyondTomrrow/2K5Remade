def align_table(season):
    s = [x for x in S['seasons'] if x['season'] == season][0]
    w('**%d** (standings order; record W-L-T):' % season)
    w('')
    w('| Division | Teams |')
    w('|---|---|')
    for c in s['conferences']:
        for d in c['divisions']:
            w('| %s | %s |' % (d['name'], ', '.join('%s %s (%s) %d-%d-%d%s' % (
                t['city'], t['name'], t['abbreviation'], t['record']['w'], t['record']['l'], t['record']['t'],
                {'division_winner': ' *', 'wild_card': ' +', None: ''}[t['finish']]) for t in d['teams'])))
    w('')
    notes = ['%s: %s' % (d['name'], d['order_note']) for c in s['conferences'] for d in c['divisions'] if d.get('order_note')]
    for n in notes:
        w('* ' + n)
    if notes:
        w('')

def members(season):
    s = [x for x in S['seasons'] if x['season'] == season][0]
    return {d['name']: sorted(t['id'] for t in d['teams']) for c in s['conferences'] for d in c['divisions']}

