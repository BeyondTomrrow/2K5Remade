def ident(i):
    if not i:
        return '-'
    return '%s %s (%s)' % (i['city'], i['name'], i['division'] or i['league'])

def link(u):
    host = u.split('/')[2].replace('www.', '')
    if 'web.archive.org' in u:
        host = 'archived PFR'
    return '[%s](%s)' % (host, u)

