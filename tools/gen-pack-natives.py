#!/usr/bin/env python3
"""Native versions of the hottest functions a known mod pack changed.

A pack's changed functions run in the interpreter (src/interp/x86_interp.c).
Most of them differ from the retail executable by a few bytes, and a handful
carry most of the frame. For those, this tool takes the converted C of the
retail function (build/gen-locals, so run after a build) and applies the same
edit the pack made to the bytes, giving src/interp/pack_native_gen.inc.c.

Each entry is guarded: at boot nfl2k5_pack_natives_init() hashes the guest bytes
listed in `guard`, and the native version is used only if they are exactly the
bytes this file was generated from. Any other pack, or any other version of
this one, runs in the interpreter as before. NFL2K5_PACK_NATIVE=0 turns them
off; NFL2K5_PACK_NATIVE_CHECK=1 runs interpreter and native side by side.

    python tools/gen-pack-natives.py
"""
import glob
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PACK = ROOT / 'mods/packs/SOFTDRINK_2K28_v0.7-v0.7/default.xbe'
OUT = ROOT / 'src/interp/pack_native_gen.inc.c'

# entry: the guest address the native version takes over at (a function start,
# or the point pack code jumps back to). edits: (exact line text or regex, new text).
SPECS = [
    dict(
        # Per-player bone blend, ~45% of all interpreted instructions. The pack
        # replaced the prologue with a jmp to its own code at 0xE6BFA (a bone
        # adjustment for one model, kept in the interpreter), which comes back
        # here; replaced the blend-rate load with a call to 0xE6CCC; and removed
        # the jne at 0x938BD.
        entry=0x00093856, base='sub_00093850',
        guard=[(0x00093850, 0x00093B39), (0x000E6BFA, 0x000E6CE3)],
        drop_until='    esp = esp & 0xFFFFFFF0u;',    # the prologue already ran
        edits=[
            ('    eax = eax + 0x96;\n',
             '    eax = eax + 0x96;\n    if (MEM16(ecx + 6) == 0x079Bu) eax = 0x64;   /* 0xE6CCC */\n'),
            ('    if (TEST_NZ(_fa, _fb)) goto loc_000938D0; /* jne: not equal / not zero */\n', ''),
        ],
    ),
]


def load_xbe(path):
    x = path.read_bytes()
    base = struct.unpack_from('<I', x, 0x104)[0]
    n = struct.unpack_from('<I', x, 0x11C)[0]
    t = struct.unpack_from('<I', x, 0x120)[0] - base
    return x, [struct.unpack_from('<IIII', x, t + i * 56 + 4) for i in range(n)]


def rd(img, va, n):
    x, secs = img
    for sva, vsz, raw, rsz in secs:
        if sva <= va < sva + vsz:
            o = raw + va - sva
            return x[o:o + n]
    raise SystemExit(f'0x{va:08X} is not in the pack executable')


def fnv(data, h=2166136261):
    for b in data:
        h = ((h ^ b) * 16777619) & 0xFFFFFFFF
    return h


def function_text(name):
    for path in sorted(glob.glob(str(ROOT / 'build/gen-locals/recomp_*.c'))):
        text = Path(path).read_text(encoding='utf-8', errors='replace').replace('\r\n', '\n')
        i = text.find(f'\nvoid {name}(void)\n{{')
        if i < 0:
            continue
        head = text.rfind('#undef RECOMP_REGS_OUT', 0, i)
        end = text.index('\n}\n', i) + 3
        return text[head:end]
    raise SystemExit(f'{name} not found in build/gen-locals (build first)')


def main():
    img = load_xbe(PACK)
    out = ['/* Generated by tools/gen-pack-natives.py; do not edit. Included at the end of\n'
           ' * interp_setup.c: native versions of a known pack\'s hottest changed functions. */\n'
           '#define RECOMP_REG_LOCALS 1\n#define RECOMP_GENERATED_CODE\n#include "recomp_funcs.h"\n\n']
    table = []
    for s in SPECS:
        text = function_text(s['base'])
        name = f"pack_native_{s['entry']:08X}"
        text = text.replace(f"void {s['base']}(void)", f'static void {name}(void)')
        text, n = re.subn(r'    RECOMP_INTERP_GATE\(0x[0-9A-Fa-f]+u\);\n', '', text)
        assert n == 1, s['base']
        if 'drop_until' in s:
            a = text.index(f"loc_{s['base'][4:]}: ;\n")
            b = text.index(s['drop_until'], a)
            b = text.index('\n', text.index('\n', b) + 1) + 1     # and its flag line
            text = text[:a] + text[b:]
        for old, new in s.get('edits', []):
            assert text.count(old) == 1, old
            text = text.replace(old, new)
        # pack code may read the caller's ebp; converted code keeps it in a local
        publish = 'g_ebp = ebp; ' if '    uint32_t ebp = 0;\n' in text else ''
        for site, target in s.get('calls', []):
            # a retail call the pack pointed at its own code: that code stays
            # interpreted, the rest of the function does not
            ret = site + 5
            text, n = re.subn(
                rf'    PUSH32\(esp, 0x{ret:08X}u\); RECOMP_ABI_CALL\(0x[0-9A-F]+u, sub_[0-9A-F]+\);[^\n]*\n',
                f'    PUSH32(esp, 0x{ret:08X}u); {publish}RECOMP_REGS_OUT(); recomp_interp_call(0x{target:08X}u); RECOMP_REGS_IN();\n',
                text)
            assert n == 1, hex(site)
        out.append(text + '\n')
        h = 2166136261
        for lo, hi in s['guard']:
            h = fnv(rd(img, lo, hi - lo), h)
        guards = ', '.join(f'{{ 0x{lo:08X}u, 0x{hi:08X}u }}' for lo, hi in s['guard'])
        table.append(f"    {{ 0x{s['entry']:08X}u, {name}, 0x{h:08X}u, {len(s['guard'])}, {{ {guards} }} }},\n")
    out.append('static const struct {\n    uint32_t va;\n    void (*fn)(void);\n    uint32_t hash;\n'
               '    int nguard;\n    uint32_t guard[4][2];\n} s_pack_native_table[] = {\n')
    out += table
    out.append('};\n')
    OUT.write_text(''.join(out), encoding='utf-8', newline='\n')
    print(f'{OUT}: {len(SPECS)} functions')


if __name__ == '__main__':
    sys.exit(main())
