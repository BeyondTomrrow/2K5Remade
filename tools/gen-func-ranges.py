"""Write the converted functions' address ranges for the interpreter.

    python tools/gen-func-ranges.py <analysis dir> <output .c>

src/interp/interp_setup.c compares each range of a mod pack's executable with
the executable the native code was converted from, and marks the functions
that differ so they run in the interpreter (src/interp/x86_interp.c).
"""
import json
import os
import sys


def main():
    analysis, out = sys.argv[1], sys.argv[2]
    funcs = json.load(open(os.path.join(analysis, "disasm", "functions.json")))
    ranges = sorted({(int(f["start"], 16), int(f["end"], 16)) for f in funcs if f.get("end")})
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ["/* Generated by tools/gen-func-ranges.py from %s. */" % os.path.basename(os.path.abspath(analysis)),
             "#include <stdint.h>",
             "const uint32_t g_nfl2k5_func_ranges[][2] = {"]
    lines += ["    { 0x%08X, 0x%08X }," % r for r in ranges if r[1] > r[0]]
    lines.append("};")
    lines.append("const unsigned g_nfl2k5_func_range_count = sizeof g_nfl2k5_func_ranges / sizeof g_nfl2k5_func_ranges[0];")
    text = "\n".join(lines) + "\n"
    if not os.path.exists(out) or open(out).read() != text:
        open(out, "w", newline="\n").write(text)
    print("[func-ranges] %d functions -> %s" % (len(ranges), out))


if __name__ == "__main__":
    # Retried: the analysis file can be mid-rewrite, or the output briefly held
    # open by a scanner or another session, which made builds fail at random.
    import time
    for attempt in range(6):
        try:
            main()
            break
        except (OSError, ValueError) as e:
            if attempt == 5:
                raise
            print("[func-ranges] retrying after: %s" % e)
            time.sleep(2)
