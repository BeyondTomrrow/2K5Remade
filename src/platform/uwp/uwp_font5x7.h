static const uint8_t *uwp_glyph(char c)
{
    unsigned i;
    if (c >= 'a' && c <= 'z') c = (char)(c - 32);
    for (i = 0; i < sizeof k_uwp_font / sizeof k_uwp_font[0]; i++)
        if (k_uwp_font[i].c == c) return k_uwp_font[i].r;
    return c == '?' ? k_uwp_font[0].r : uwp_glyph('?');
}

